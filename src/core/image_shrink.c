/*
 * image_shrink.c — automatic, size-budget-aware image reducer.
 *
 * Called after the user picks a target partition size (32/64/128MB/custom)
 * and the built/patched image comes out larger than that budget. Tries a
 * sequence of safe, automatic reductions first; only asks the user to
 * approve a feature trade-off (e.g. dropping extra languages) if automatic
 * steps alone can't close the gap.
 */

#include "image_shrink.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdarg.h>
#include <dirent.h>
#include <sys/stat.h>

/* ---- helpers --------------------------------------------------------- */

/* Sums file sizes under `path` via `du`, since a hand-rolled recursive
 * walk adds nothing `du -sb` doesn't already give us correctly. */
static int64_t dir_size_recursive(const char *path) {
    char cmd[600];
    snprintf(cmd, sizeof(cmd), "du -sb '%s' 2>/dev/null | cut -f1", path);
    FILE *fp = popen(cmd, "r");
    if (!fp) return 0;
    int64_t size = 0;
    if (fscanf(fp, "%lld", (long long *)&size) != 1) size = 0;
    pclose(fp);
    return size;
}

static bool run_cmd(const char *fmt, ...) {
    char cmd[1024];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(cmd, sizeof(cmd), fmt, ap);
    va_end(ap);
    return system(cmd) == 0;
}

/* Strategy 1: strip debug/sanitizer runtimes that have no business in a
 * release build (matches the libclang_rt.ubsan_standalone-aarch64-android.so
 * class of bloat found when auditing the BF7 ramdisk). */
static int64_t strategy_strip_debug_runtimes(const char *workdir) {
    int64_t freed = 0;
    const char *patterns[] = {
        "lib*/libclang_rt.*san*.so",
        "lib*/libasan.so",
        "bin/strace",
        "bin/gdbserver",
        NULL
    };
    for (int i = 0; patterns[i]; i++) {
        char find_cmd[512];
        snprintf(find_cmd, sizeof(find_cmd),
                 "find '%s' -path '*/%s' -printf '%%s\\n' -delete 2>/dev/null",
                 workdir, patterns[i]);
        FILE *fp = popen(find_cmd, "r");
        if (!fp) continue;
        char line[64];
        while (fgets(line, sizeof(line), fp)) freed += atoll(line);
        pclose(fp);
    }
    return freed;
}

/* Strategy 2: drop static binaries never referenced by any UI menu action.
 * The reference list comes from menu_actions.c at build time (generated),
 * so this never removes something a button actually calls. */
static int64_t strategy_strip_unreferenced_binaries(const char *workdir) {
    int64_t freed = 0;
    char manifest[512];
    snprintf(manifest, sizeof(manifest), "%s/.referenced_binaries", workdir);
    FILE *ref = fopen(manifest, "r");
    if (!ref) return 0; /* manifest generated by build step; skip if absent */

    char referenced[256][128];
    int ref_count = 0;
    while (ref_count < 256 && fgets(referenced[ref_count], 128, ref))
        ref_count++;
    fclose(ref);

    char bin_dir[512];
    snprintf(bin_dir, sizeof(bin_dir), "%s/system/bin", workdir);
    DIR *d = opendir(bin_dir);
    if (!d) return 0;
    struct dirent *ent;
    while ((ent = readdir(d))) {
        if (ent->d_name[0] == '.') continue;
        bool is_referenced = false;
        for (int i = 0; i < ref_count; i++) {
            if (strstr(referenced[i], ent->d_name)) { is_referenced = true; break; }
        }
        if (!is_referenced) {
            char full[768];
            snprintf(full, sizeof(full), "%s/%s", bin_dir, ent->d_name);
            struct stat st;
            if (stat(full, &st) == 0) {
                if (remove(full) == 0) freed += st.st_size;
            }
        }
    }
    closedir(d);
    return freed;
}

/* Strategy 3: recompress ramdisk at the strongest level the device's kernel
 * actually supports. NOTE: always check /proc/config.gz CONFIG_RD_* on the
 * real device before enabling anything beyond gzip — see twrp-tecno-bf7
 * notes: this device's kernel only has CONFIG_RD_GZIP, so gzip -9 is the
 * ceiling there. */
static int64_t strategy_recompress_ramdisk(const char *workdir,
                                            const char *supported_algo) {
    char ramdisk_cpio[512], ramdisk_comp[512];
    snprintf(ramdisk_cpio, sizeof(ramdisk_cpio), "%s/ramdisk.cpio", workdir);
    snprintf(ramdisk_comp, sizeof(ramdisk_comp), "%s/ramdisk.cpio.%s",
             workdir, supported_algo);

    struct stat before;
    if (stat(ramdisk_comp, &before) != 0) before.st_size = 0;

    bool ok = false;
    if (strcmp(supported_algo, "gzip") == 0) {
        ok = run_cmd("gzip -9 -f -c '%s' > '%s'", ramdisk_cpio, ramdisk_comp);
    } else if (strcmp(supported_algo, "lzma") == 0) {
        ok = run_cmd("lzma -9 -f -c '%s' > '%s'", ramdisk_cpio, ramdisk_comp);
    } else if (strcmp(supported_algo, "xz") == 0) {
        ok = run_cmd("xz -9e -f -c '%s' > '%s'", ramdisk_cpio, ramdisk_comp);
    }
    if (!ok) return 0;

    struct stat after;
    if (stat(ramdisk_comp, &after) != 0) return 0;
    int64_t freed = before.st_size - after.st_size;
    return freed > 0 ? freed : 0;
}

/* Strategy 4: strip ELF debug/symbol sections from remaining binaries/libs.
 * Purely metadata removal — zero functional impact. */
static int64_t strategy_strip_symbols(const char *workdir) {
    int64_t before = dir_size_recursive(workdir);
    run_cmd("find '%s' -type f \\( -name '*.so' -o -path '*/bin/*' \\) "
            "-exec sh -c 'file \"$1\" | grep -q ELF && strip --strip-unneeded \"$1\" 2>/dev/null' _ {} \\;",
            workdir);
    int64_t after = dir_size_recursive(workdir);
    int64_t freed = before - after;
    return freed > 0 ? freed : 0;
}

/* ---- trade-off catalogue (only used if automatic steps aren't enough) -- */

static bool tradeoff_apply_extra_languages(const char *workdir) {
    /* Keeps en/en-US + the device's default locale, drops the rest from any
     * bundled locale/strings directories. The "default locale" is read from
     * device.conf so this stays device-agnostic. */
    return run_cmd(
        "find '%s' -path '*/res/values-*' -maxdepth 6 -type d "
        "! -name 'values-en*' -exec rm -rf {} + 2>/dev/null", workdir);
}

static bool tradeoff_apply_theme_assets(const char *workdir) {
    /* Drop high-res theme variants, keep the base density the UI renders at */
    return run_cmd(
        "find '%s' -path '*/theme/*' \\( -name '*@2x*' -o -name '*@3x*' \\) "
        "-delete 2>/dev/null", workdir);
}

static bool tradeoff_apply_unused_fonts(const char *workdir) {
    return run_cmd(
        "find '%s' -path '*/fonts/*' ! -name 'DejaVuSans.ttf' "
        "-delete 2>/dev/null", workdir);
}

/* ---- main entry point -------------------------------------------------*/

cf_shrink_result_t cf_shrink_image_to_fit(
    const char *workdir,
    int64_t current_size_bytes,
    int64_t target_partition_size,
    cf_ui_prompt_tradeoffs_fn prompt_fn
) {
    int64_t overage = current_size_bytes - target_partition_size;
    if (overage <= 0) return CF_SHRINK_OK;

    /* Phase 1: automatic, always-safe strategies, cheapest/least-risky first */
    overage -= strategy_strip_debug_runtimes(workdir);
    if (overage <= 0) return CF_SHRINK_OK;

    overage -= strategy_strip_unreferenced_binaries(workdir);
    if (overage <= 0) return CF_SHRINK_OK;

    overage -= strategy_recompress_ramdisk(workdir, "gzip");
    if (overage <= 0) return CF_SHRINK_OK;

    overage -= strategy_strip_symbols(workdir);
    if (overage <= 0) return CF_SHRINK_OK;

    /* Phase 2: automatic steps weren't enough — only now involve the user */
    cf_shrink_tradeoff_t catalogue[] = {
        { "extra_languages", "Remove extra language packs (keep English + device default)",
          0, tradeoff_apply_extra_languages },
        { "theme_hires_assets", "Remove high-resolution theme assets",
          0, tradeoff_apply_theme_assets },
        { "unused_fonts", "Remove bundled fonts except the default UI font",
          0, tradeoff_apply_unused_fonts },
    };
    int catalogue_count = sizeof(catalogue) / sizeof(catalogue[0]);

    if (!prompt_fn) return CF_SHRINK_FAILED; /* no UI available to ask */

    int *chosen = calloc(catalogue_count, sizeof(int));
    int chosen_count = prompt_fn(catalogue, catalogue_count, overage, chosen);

    if (chosen_count <= 0) {
        free(chosen);
        return CF_SHRINK_USER_CANCELLED;
    }

    for (int i = 0; i < chosen_count; i++) {
        int idx = chosen[i];
        if (idx < 0 || idx >= catalogue_count) continue;
        if (catalogue[idx].apply(workdir)) {
            /* re-measure rather than trust the estimate, since actual
             * savings depend on what's really present in this ramdisk */
        }
    }
    free(chosen);

    int64_t new_size = dir_size_recursive(workdir);
    if (new_size <= target_partition_size) return CF_SHRINK_OK_WITH_TRADEOFF;
    return CF_SHRINK_FAILED;
}
